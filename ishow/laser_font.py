ADVANCE = 5      # glyph width 4 + 1 gap
LINE_HEIGHT = 9  # glyph height 6 + 3 gap


def text_strokes(lines):
    """Lay out up to a few lines of text, centred, scaled into the -0.9..0.9 square.
    Returns a list of strokes (polylines) in laser coordinates."""
    lines = [ln.upper() for ln in lines if ln.strip()] or [""]
    width = max(max(len(ln) * ADVANCE - 1, 1) for ln in lines)
    height = len(lines) * LINE_HEIGHT - 3
    scale = 1.8 / max(width, height)
    strokes = []
    for row, line in enumerate(lines):
        line_w = len(line) * ADVANCE - 1
        x0 = -line_w / 2
        y0 = height / 2 - 6 - row * LINE_HEIGHT
        for i, ch in enumerate(line):
            for stroke in GLYPHS.get(ch, GLYPHS["?"]):
                strokes.append([((x0 + i * ADVANCE + x) * scale, (y0 + y) * scale) for x, y in stroke])
    return strokes
