#!/usr/bin/env python3
"""Install the WinUSB driver for the iShow box (USB 3333:6666) without Zadig.

Uses only what's built into Windows 10/11, the same steps Zadig takes:
  1. an .inf that binds Windows' own WinUSB driver to USB\\VID_3333&PID_6666
     (no driver code of our own: winusb.sys is Microsoft's, already signed);
  2. a catalog (.cat) for it, made with Windows' built-in catalog API
     (CryptCATCDF*, as Microsoft's makecat tool does);
  3. the catalog signed with a certificate created on this PC, which is then
     trusted only on this PC; its private key is deleted straight after
     signing, so nothing else can ever be signed with it;
  4. pnputil /add-driver ... /install.

Needs administrator rights: ishow_app.py's "Install driver" button starts this
with a Windows elevation (UAC) prompt.

    python winusb_install.py --install --log install.log   (as administrator)
    python winusb_install.py --dry-run DIR                 (just write the files, any OS)
"""
import argparse
import ctypes
import datetime
import os
import subprocess
import tempfile
import traceback

VID, PID = 0x3333, 0x6666
INTERFACE_GUID = "{6E5A0A1F-3B2C-4D8E-9F1A-2C7B5E8D4A31}"   # fixed, unique to this project
INF_NAME, CAT_NAME = "ishow_winusb.inf", "ishow_winusb.cat"
CERT_SUBJECT = "CN=iShow Laser box driver (this PC only)"


def inf_text():
    hw = f"USB\\VID_{VID:04X}&PID_{PID:04X}"
    today = datetime.date.today().strftime("%m/%d/%Y")
    models = "\n".join(f"[Laser.{arch}]\n%DeviceName% = USB_Install, {hw}\n"
                       for arch in ("NTamd64", "NTx86", "NTarm64"))
    return f"""; WinUSB for the iShow laser box (Guicard13 board, {hw})
; Uses Windows' own winusb.sys; generated by winusb_install.py

[Version]
Signature   = "$Windows NT$"
Class       = USBDevice
ClassGUID   = {{88BAE032-5A81-49f0-BC3D-A4FF138216D6}}
Provider    = %ProviderName%
CatalogFile = {CAT_NAME}
DriverVer   = {today}, 1.0.0.0

[Manufacturer]
%ProviderName% = Laser, NTamd64, NTx86, NTarm64

{models}
[USB_Install]
Include = winusb.inf
Needs   = WINUSB.NT

[USB_Install.Services]
Include = winusb.inf
Needs   = WINUSB.NT.Services

[USB_Install.HW]
AddReg = Dev_AddReg

[Dev_AddReg]
HKR,,DeviceInterfaceGUIDs,0x10000,"{INTERFACE_GUID}"

[Strings]
ProviderName = "iShow Laser (local)"
DeviceName   = "iShow laser box"
"""


def cdf_text(folder):
    return f"""[CatalogHeader]
Name={CAT_NAME}
ResultDir={folder}
PublicVersion=0x0000001
CatalogVersion=2
HashAlgorithms=SHA256
EncodingType=0x00010001
CATATTR1=0x10010001:OSAttr:2:6.1,2:6.2,2:6.3,2:10.0

[CatalogFiles]
<hash>{INF_NAME}={os.path.join(folder, INF_NAME)}
<hash>{INF_NAME}ATTR1=0x10010001:OSAttr:2:6.1,2:6.2,2:6.3,2:10.0
"""


def make_catalog(folder):
    """Build the .cat from the .cdf with wintrust.dll (what makecat.exe does)."""
    cdf_path = os.path.join(folder, "ishow_winusb.cdf")
    with open(cdf_path, "w", encoding="utf-16") as f:
        f.write(cdf_text(folder))
    wt = ctypes.WinDLL("wintrust", use_last_error=True)
    errors = []
    CALLBACK = ctypes.WINFUNCTYPE(None, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_wchar_p)
    on_error = CALLBACK(lambda area, code, line: errors.append(f"area {area:#x} error {code:#x}: {line}"))
    wt.CryptCATCDFOpen.restype = ctypes.c_void_p
    wt.CryptCATCDFOpen.argtypes = [ctypes.c_wchar_p, CALLBACK]
    wt.CryptCATCDFEnumMembersByCDFTagEx.restype = ctypes.c_void_p   # LPWSTR, kept raw
    wt.CryptCATCDFEnumMembersByCDFTagEx.argtypes = [ctypes.c_void_p, ctypes.c_void_p, CALLBACK,
                                                     ctypes.POINTER(ctypes.c_void_p), ctypes.c_bool,
                                                     ctypes.c_void_p]
    wt.CryptCATCDFClose.argtypes = [ctypes.c_void_p]
    cdf = wt.CryptCATCDFOpen(cdf_path, on_error)
    if not cdf:
        raise RuntimeError(f"CryptCATCDFOpen failed ({ctypes.get_last_error():#x}) {errors}")
    member, tag = ctypes.c_void_p(), None
    while True:   # walking the members makes wintrust hash each file
        tag = wt.CryptCATCDFEnumMembersByCDFTagEx(cdf, tag, on_error, ctypes.byref(member), True, None)
        if not tag:
            break
    if not wt.CryptCATCDFClose(cdf):
        raise RuntimeError(f"CryptCATCDFClose failed ({ctypes.get_last_error():#x}) {errors}")
    cat = os.path.join(folder, CAT_NAME)
    if errors or not os.path.exists(cat):
        raise RuntimeError(f"catalog not created: {errors}")
    return cat


def powershell(script, log):
    r = subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", script],
                       capture_output=True, text=True)
    log(r.stdout.strip())
    if r.returncode != 0:
        raise RuntimeError(f"PowerShell step failed: {r.stderr.strip()}")
    return r.stdout


def sign_catalog(cat, log):
    """Self-signed code-signing certificate, trusted on this PC only; private key deleted after."""
    cer = os.path.join(os.path.dirname(cat), "ishow_local.cer")
    script = f"""
$ErrorActionPreference = 'Stop'
$c = New-SelfSignedCertificate -Type CodeSigningCert -Subject '{CERT_SUBJECT}' `
     -CertStoreLocation Cert:\\LocalMachine\\My -HashAlgorithm SHA256 -NotAfter (Get-Date).AddYears(30)
Export-Certificate -Cert $c -FilePath '{cer}' | Out-Null
Import-Certificate -FilePath '{cer}' -CertStoreLocation Cert:\\LocalMachine\\Root | Out-Null
Import-Certificate -FilePath '{cer}' -CertStoreLocation Cert:\\LocalMachine\\TrustedPublisher | Out-Null
$s = Set-AuthenticodeSignature -FilePath '{cat}' -Certificate $c -HashAlgorithm SHA256
Remove-Item -Path ('Cert:\\LocalMachine\\My\\' + $c.Thumbprint) -DeleteKey
Write-Output ('signature: ' + $s.Status)
if ($s.Status -ne 'Valid') {{ exit 2 }}
"""
    powershell(script, log)


def install(log):
    if os.name != "nt":
        raise RuntimeError("this installer only runs on Windows")
    if not ctypes.windll.shell32.IsUserAnAdmin():
        raise RuntimeError("needs administrator rights (use the app's Install driver button)")
    # ProgramData has no spaces in its path (user names often do), which keeps the catalog step simple
    folder = os.path.join(os.environ.get("ProgramData", tempfile.gettempdir()), "iShowLaser", "driver")
    os.makedirs(folder, exist_ok=True)
    for name in os.listdir(folder):
        os.remove(os.path.join(folder, name))
    inf = os.path.join(folder, INF_NAME)
    with open(inf, "w", encoding="ascii", newline="\r\n") as f:
        f.write(inf_text())
    log(f"wrote {inf}")
    cat = make_catalog(folder)
    log(f"made {cat}")
    sign_catalog(cat, log)
    r = subprocess.run(["pnputil", "/add-driver", inf, "/install"], capture_output=True, text=True)
    log(r.stdout.strip() + ("\n" + r.stderr.strip() if r.stderr.strip() else ""))
    if r.returncode not in (0, 3010):   # 3010 = done, restart suggested
        raise RuntimeError(f"pnputil failed (exit code {r.returncode})")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--install", action="store_true", help="install the driver (administrator)")
    ap.add_argument("--log", help="write progress and the final RESULT line to this file")
    ap.add_argument("--dry-run", metavar="DIR", help="only write the .inf and .cdf into DIR")
    args = ap.parse_args()
    if args.dry_run:
        os.makedirs(args.dry_run, exist_ok=True)
        with open(os.path.join(args.dry_run, INF_NAME), "w") as f:
            f.write(inf_text())
        with open(os.path.join(args.dry_run, "ishow_winusb.cdf"), "w") as f:
            f.write(cdf_text(os.path.abspath(args.dry_run)))
        print("wrote", INF_NAME, "and ishow_winusb.cdf to", args.dry_run)
        return
    lines = []

    def log(msg):
        if msg:
            lines.append(msg)
            print(msg)
    try:
        install(log)
        lines.append("RESULT: OK")
    except Exception as e:  # noqa: BLE001 - reported to the app
        lines.append(traceback.format_exc())
        lines.append(f"RESULT: FAILED: {e}")
    if args.log:
        with open(args.log, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    print(lines[-1])


if __name__ == "__main__":
    main()
